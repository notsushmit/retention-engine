"""The drift comparison on the synthetic path (configs/ops.yaml, R1; synthetic data only).

Synthetic data generated by hand-set rules; it is not KKBox data and says nothing about KKBox
customers. The registered replay of the 20% sample needs the Valkey store and is not run here; this
is the same comparison on the synthetic tables:

- reference features: the P2 main rows at the fit snapshots; reference predictions: the P2 main rows
  of a later snapshot the classifiers were not fit on (different rows, so each column of the
  reference table is filled for the rows it comes from and empty for the others);
- current: the P2 main rows at the store date, features and the final probabilities of the same
  rows;
- the shift: listening in the month before the store date halved in the user logs (total_secs times
  0.5, every count halved and rounded down); transactions are never touched; features are rebuilt by
  the unchanged feature code from the shifted logs.

No outcome is read. Final probabilities are the clip, pool-adjacent-violators and clip of the raw
probabilities (no Platt step on synthetic data).
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path
from typing import Any

import duckdb
import numpy as np
import pandas as pd

from retention.features.build import FeaturePaths, build
from retention.features.spec import PRIMARY_FEATURES
from retention.models.calibration import calibrate
from retention.ops import drift as dr
from retention.synthetic import SYNTHETIC_SENTENCE
from retention.synthetic.pipeline import Setup, feature_rows, fit_models, p2_main_keys

HORIZONS = (7, 30, 59)


class Identity:
    """A calibrator that changes nothing (no Platt step on synthetic data)."""

    def predict(self, p: np.ndarray) -> np.ndarray:
        return np.asarray(p, dtype=float)


def final_probabilities(models: dict, rows: pd.DataFrame) -> pd.DataFrame:
    raw = np.column_stack([models[h].predict(rows)[0] for h in HORIZONS])
    final = calibrate(raw, [Identity() for _ in HORIZONS])["final"]
    return pd.DataFrame(final, columns=dr.PREDICTIONS)


def _day(value: Any) -> date:
    return date.fromisoformat(str(value))


def shift_logs(src: Path, dst: Path, first: date, last: date) -> int:
    """Halve listening dated first..last; return the number of rows changed."""
    lo, hi = (
        first.year * 10000 + first.month * 100 + first.day,
        last.year * 10000 + last.month * 100 + last.day,
    )
    hit = f"date >= {lo} and date <= {hi}"
    duckdb.sql(
        f"""copy (select msno, date,
          case when {hit} then num_25 // 2 else num_25 end as num_25,
          case when {hit} then num_50 // 2 else num_50 end as num_50,
          case when {hit} then num_75 // 2 else num_75 end as num_75,
          case when {hit} then num_985 // 2 else num_985 end as num_985,
          case when {hit} then num_100 // 2 else num_100 end as num_100,
          case when {hit} then num_unq // 2 else num_unq end as num_unq,
          case when {hit} then total_secs * 0.5 else total_secs end as total_secs
          from '{src}') to '{dst}' (format parquet)"""
    )
    return int(duckdb.sql(f"select count(*) from '{src}' where {hit}").fetchone()[0])


def daily_events(setup: Setup, month: str) -> pd.Series:
    """Transactions plus listening rows per day of a month (YYYY-MM), zero-filled."""
    y, m = int(month[:4]), int(month[5:7])
    lo, hi = y * 10000 + m * 100 + 1, y * 10000 + m * 100 + 31
    tx, logs = f"{setup.interim}/transactions.parquet", f"{setup.interim}/user_logs.parquet"
    q = f"""select d, count(*) n from (
        select transaction_date d from '{tx}' union all select date d from '{logs}')
        where d between {lo} and {hi} group by d order by d"""
    counts = duckdb.sql(q).df().set_index("d").n
    index = [y * 10000 + m * 100 + k for k in range(1, pd.Period(month).days_in_month + 1)]
    return counts.reindex(index, fill_value=0)


def _reference(setup: Setup, models: dict, cfg: dict[str, Any]) -> tuple[pd.DataFrame, dict]:
    fit = [_day(s) for s in cfg["reference_fit_snapshots"]]
    pred_snap = _day(cfg["reference_prediction_snapshot"])
    feats = feature_rows(setup, fit)
    keys = p2_main_keys(setup, fit)
    feats = feats.merge(keys, on=["msno", "snapshot_date"], validate="1:1")
    pred_rows = feature_rows(setup, [pred_snap]).merge(
        p2_main_keys(setup, [pred_snap]), on=["msno", "snapshot_date"], validate="1:1"
    )
    preds = final_probabilities(models, pred_rows)
    ref = pd.concat([feats[PRIMARY_FEATURES], preds], ignore_index=True)
    info = {
        "features": f"P2 main rows at {', '.join(str(s) for s in fit)}",
        "feature_rows": len(feats),
        "predictions": f"final probabilities of the P2 main rows at {pred_snap}",
        "prediction_rows": len(preds),
    }
    return ref, info


def _current(setup: Setup, models: dict, snapshot: date, features: Path | None = None):
    rows = feature_rows(setup, [snapshot], features).merge(
        p2_main_keys(setup, [snapshot]), on=["msno", "snapshot_date"], validate="1:1"
    )
    preds = final_probabilities(models, rows)
    return pd.concat([rows[PRIMARY_FEATURES].reset_index(drop=True), preds], axis=1)


def run(setup: Setup | None = None) -> dict[str, Any]:
    """The unshifted and the shifted comparison; writes the reports and the GET /drift file."""
    setup = setup or Setup()
    cfg = setup.raw["drift"]
    out = setup.processed / "ops"
    setup.mark(out)
    if not (out / dr.DEFAULTS_FILE).exists():
        raise RuntimeError(
            "log the library defaults first (python -m retention.synthetic drift --defaults)"
        )
    defaults = json.loads((out / dr.DEFAULTS_FILE).read_text())
    models = fit_models(setup)
    reference, ref_info = _reference(setup, models, cfg)
    snapshot = _day(cfg["current_snapshot"])

    current_plain = _current(setup, models, snapshot)
    unshifted = dr.run_report(reference, current_plain, out)

    logs = setup.interim / "user_logs.parquet"
    shifted_logs = out / "synthetic_user_logs_shifted.parquet"
    first, last = _day(cfg["shift_first_day"]), _day(cfg["shift_last_day"])
    changed = shift_logs(logs, shifted_logs, first, last)
    shifted_features = out / "synthetic_features_shifted.parquet"
    build(
        FeaturePaths(setup.processed, (shifted_logs, setup.interim / "user_logs_v2.parquet")),
        setup.cfg,
        [snapshot],
        out=shifted_features,
    )
    current_shifted = _current(setup, models, snapshot, shifted_features)
    shifted = dr.run_report(reference, current_shifted, out)

    margin = dr.margin_result(unshifted, shifted)
    ref_days = daily_events(setup, str(cfg["batch_reference_month"]))
    cur_days = daily_events(setup, str(cfg["batch_current_month"]))
    batch = dr.batch_size_indicator(ref_days, cur_days)
    reference_desc = {**ref_info, "note": "predictions and features come from different rows"}
    current_desc = {
        "store_date": str(snapshot),
        "rows": shifted["current_rows"],
        "shift": f"listening halved in the logs dated {first} to {last} ({changed} rows)",
    }
    common = {"synthetic": True, "label": SYNTHETIC_SENTENCE, "sentence": dr.LABEL}
    dr.write_json(out / "synthetic_drift_unshifted.json", {**common, "shifted": False, **unshifted})
    dr.write_json(out / "synthetic_drift_shifted.json", {**common, "shifted": True, **shifted})
    latest = dr.body(
        shifted_report=shifted,
        margin=margin,
        shifted=True,
        batch=batch,
        reference=reference_desc,
        current=current_desc,
        synthetic=True,
        defaults=defaults,
    )
    dr.write_json(out / "drift_latest.json", latest)
    return {
        "unshifted": unshifted,
        "shifted": shifted,
        "margin": margin,
        "batch": batch,
        "latest": latest,
    }
