"""The small-data path: synthetic tables -> labels -> features -> a classifier (all synthetic).

Synthetic data generated by hand-set rules; it is not KKBox data and says nothing about KKBox
customers. This module stages the generated tables under the file names the unchanged label and
feature code reads, runs that code with configs/synthetic_kkbox.yaml, and fits a small LightGBM
classifier on the synthetic rows. Nothing here reads a KKBox path: every directory comes from
that config, and `check_synthetic_paths` refuses any path outside data/synthetic.

Every report and model file written here carries the synthetic label and a SYNTHETIC marker sits
beside it. Metrics computed here are labelled synthetic and are never quoted beside KKBox figures.
"""

from __future__ import annotations

import contextlib
import io
import json
import shutil
import time
from datetime import date
from pathlib import Path
from typing import Any

import duckdb
import pandas as pd
import yaml
from sklearn.metrics import roc_auc_score

from retention.data.clean import write_validation
from retention.data.sample import sample_dir
from retention.features.build import FeaturePaths, build
from retention.features.spec import PRIMARY_FEATURES
from retention.labels.__main__ import run_clean, run_labels, run_quality_cmd, run_timeline
from retention.labels.config import LabelConfig, parse_label_config
from retention.models.classifier import Classifier
from retention.models.protocol import Threads
from retention.synthetic import SYNTHETIC_SENTENCE
from retention.synthetic.generate import MARKER, generate

CONFIG = Path("configs/synthetic_kkbox.yaml")
ROOT = Path("data/synthetic")
GENERATED = ROOT / "generated"
STAGED = {  # generated file -> the name the unchanged pipeline reads
    "synthetic_transactions": "transactions",
    "synthetic_transactions_v2": "transactions_v2",
    "synthetic_user_logs": "user_logs",
    "synthetic_user_logs_v2": "user_logs_v2",
    "synthetic_members": "members_v3",
    "synthetic_train": "train",
    "synthetic_train_v2": "train_v2",
}
CATEGORICAL = ["last_payment_method_id", "registered_via", "segment", "paid_state", "last_row_kind"]
FIXED = {
    "deterministic": True,
    "force_col_wise": True,
    "bagging_fraction": 1.0,
    "feature_fraction": 1.0,
    "verbosity": -1,
}


def check_synthetic_paths(*paths: Path, root: Path = ROOT) -> None:
    """Refuse any path that is not inside the synthetic folder."""
    base = root.resolve()
    for p in paths:
        if base not in Path(p).resolve().parents and Path(p).resolve() != base:
            raise ValueError(f"{p} is outside {root}: the synthetic path reads nothing else")


class Setup:
    """The synthetic config, parsed once, with the folders it names."""

    def __init__(self, config: Path = CONFIG, root: Path = ROOT):
        raw = yaml.safe_load(config.read_text())
        if raw.get("synthetic") is not True:
            raise ValueError(f"{config} is not a synthetic profile")
        self.raw = raw
        self.cfg: LabelConfig = parse_label_config(raw["labels"])
        fraction = float(raw["data"]["sample_fraction"])
        self.root = root
        self.interim = sample_dir(Path(raw["data"]["interim_dir"]), fraction)
        self.processed = sample_dir(self.cfg.processed_dir, fraction)
        check_synthetic_paths(self.interim, self.processed, root=root)

    def mark(self, *dirs: Path) -> None:
        for d in dirs:
            d.mkdir(parents=True, exist_ok=True)
            (d / MARKER).write_text(SYNTHETIC_SENTENCE + "\n")


def stage(setup: Setup, generated: Path) -> list[str]:
    """Copy the generated tables to the names the label and feature code reads."""
    setup.mark(setup.interim, setup.processed)
    names = []
    for src, dst in STAGED.items():
        shutil.copyfile(generated / f"{src}.parquet", setup.interim / f"{dst}.parquet")
        names.append(f"{dst}.parquet")
    return names


def labels_and_features(setup: Setup) -> dict[str, Any]:
    """The unchanged clean, timeline, quality, labels and feature code, on the synthetic tables."""
    t0 = time.time()
    cfg, interim, out = setup.cfg, setup.interim, setup.processed
    logs = " union all ".join(
        f"select msno, date from '{interim / f}'"
        for f in ("user_logs.parquet", "user_logs_v2.parquet")
    )
    with contextlib.redirect_stdout(io.StringIO()):
        run_clean(interim, out, cfg)
        run_timeline(out, cfg)
        run_quality_cmd(out, f"({logs})", cfg)
        run_labels(out, cfg)
        paths = FeaturePaths(
            processed=out, logs=(interim / "user_logs.parquet", interim / "user_logs_v2.parquet")
        )
        report = build(paths, cfg, None)
    write_validation(out, "features", report)
    write_validation(out, "synthetic", {"synthetic": True, "label": SYNTHETIC_SENTENCE})
    rows = duckdb.sql(f"select count(*) from read_parquet('{paths.out}')").fetchone()[0]
    return {
        "feature_rows": int(rows),
        "feature_snapshots": len(report["per_snapshot"]) if "per_snapshot" in report else None,
        "seconds": round(time.time() - t0, 1),
    }


def training_rows(setup: Setup, snapshots: list[date], horizon: int) -> pd.DataFrame:
    """P2 main rows (expiring within 30 days, paid or 100%-discount) with a known outcome."""
    out = setup.processed
    snaps = ", ".join(f"date '{s}'" for s in snapshots)
    lab = duckdb.sql(
        f"""select msno, snapshot_date, churned_{horizon} as y
        from read_parquet('{out}/labels.parquet')
        where snapshot_date in ({snaps}) and in_exp30
          and segment in ('paid', 'discount100_only') and churned_{horizon} is not null"""
    ).df()
    cols = ", ".join(f'"{c}"' for c in PRIMARY_FEATURES)
    feat = duckdb.sql(
        f"select msno, snapshot_date, {cols} from read_parquet('{out}/features.parquet') "
        f"where snapshot_date in ({snaps})"
    ).df()
    df = lab.merge(feat, on=["msno", "snapshot_date"], how="inner", validate="one_to_one")
    df["y"] = df.y.astype(int)
    return df


def train(setup: Setup) -> dict[str, Any]:
    """Fit one small classifier per horizon on the fit snapshots; score the score snapshot."""
    t0 = time.time()
    tr = setup.raw["training"]
    fit = [date.fromisoformat(str(s)) for s in tr["fit_snapshots"]]
    score = date.fromisoformat(str(tr["score_snapshot"]))
    columns = list(PRIMARY_FEATURES)
    report: dict[str, Any] = {
        "synthetic": True,
        "label": SYNTHETIC_SENTENCE,
        "metrics_note": "Computed on synthetic data; says nothing about KKBox.",
        "fit_snapshots": [str(s) for s in fit],
        "score_snapshot": str(score),
        "settings": {
            k: tr[k]
            for k in ("num_leaves", "n_estimators", "learning_rate", "min_child_samples", "seed")
        },
        "horizons": {},
    }
    models = setup.processed / "models"
    setup.mark(models)
    for h in tr["horizons"]:
        fit_rows = training_rows(setup, fit, h)
        score_rows = training_rows(setup, [score], h)
        candidate = {
            k: tr[k] for k in ("num_leaves", "n_estimators", "learning_rate", "min_child_samples")
        }
        clf = Classifier(
            columns, CATEGORICAL, candidate, FIXED, Threads(int(tr["threads"])), int(tr["seed"])
        )
        clf.fit(fit_rows)
        p, unseen = clf.predict(score_rows)
        both = score_rows.y.nunique() == 2
        report["horizons"][str(h)] = {
            "fit_rows": len(fit_rows),
            "fit_events": int(fit_rows.y.sum()),
            "score_rows": len(score_rows),
            "score_events": int(score_rows.y.sum()),
            "auc_synthetic": float(roc_auc_score(score_rows.y, p)) if both else None,
            "unseen_levels": unseen,
            "feature_columns": len(columns),
        }
        clf.booster.save_model(str(models / f"synthetic_classifier_{h}.txt"))
    report["seconds"] = round(time.time() - t0, 1)
    (models / "synthetic_train_report.json").write_text(json.dumps(report, indent=1) + "\n")
    return report


def run_all(setup: Setup | None = None, generated: Path = GENERATED) -> dict[str, Any]:
    """Generate, stage, build labels and features, train. Returns one synthetic report."""
    t0 = time.time()
    setup = setup or Setup()
    gen = generate(generated)
    stage(setup, generated)
    lf = labels_and_features(setup)
    tr = train(setup)
    report = {
        "synthetic": True,
        "label": SYNTHETIC_SENTENCE,
        "generate": {k: gen[k] for k in ("customers", "total_bytes", "rows")},
        "labels_and_features": lf,
        "train": tr,
        "seconds": round(time.time() - t0, 1),
    }
    (setup.processed / "synthetic_pipeline_report.json").write_text(
        json.dumps(report, indent=1) + "\n"
    )
    return report
