"""Synthetic subscription data in the shape of the KKBox tables (configs/ops.yaml, R3).

Synthetic data generated by hand-set rules; it is not KKBox data and says nothing about KKBox
customers. Every constant below was set by hand. None was computed from, copied from or tuned
against a KKBox file, table, report or model, and this module opens no KKBox path and imports
none of the pipeline's data readers (tests/test_synthetic.py checks both).

The simulation: each customer has a hand-set engagement level and an auto-renew habit. A
customer renews at each expiry with a probability that rises with both. A customer who does
not renew lapses; some cancel shortly before, some return later. Listening days follow the
engagement level and thin out before a lapse. Rows after the last data day are cut, so the
tables look like a recording that stops on DATA_END.

Written files are named synthetic_*.parquet beside a SYNTHETIC marker file.
"""

from __future__ import annotations

import json
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import yaml

from retention.synthetic import SYNTHETIC_SENTENCE

OPS_CONFIG = Path("configs/ops.yaml")
MARKER = "SYNTHETIC"

# Calendar (set by hand).
DATA_START = date(2016, 1, 1)
DATA_END = date(2016, 12, 31)
LAST_JOIN = date(2016, 9, 30)
SIMULATION_END = date(2017, 3, 31)  # rows after DATA_END are cut after the simulation

# Plans: days -> (list price, share of customers choosing it). Set by hand.
PLANS = {7: (50, 0.10), 30: (149, 0.75), 90: (399, 0.15)}
PAYMENT_METHODS = (38, 39, 40, 41)
CITIES = (1, *range(3, 23))  # 2 left out: the feature code's vocabulary check refuses it
REGISTERED_VIA = (3, 4, 7, 9)

# Shares of customers by kind (set by hand).
TRIAL_ONLY_SHARE = 0.04
DISCOUNT100_SHARE = 0.015
DISCOUNTED_ROW_SHARE = 0.10  # paid rows at half price
CANCEL_BEFORE_LAPSE = 0.30
RETURN_AFTER_LAPSE = 0.25
RETURN_GAP_DAYS = (31, 120)
CANCEL_LEAD_DAYS = (1, 10)
LATE_RENEW_DAYS = 5  # a customer without auto-renew renews 0 to this many days after expiry

# Renewal probability: sigmoid(R0 + R_AUTO * auto_renew + R_ENG * (engagement - 0.4)).
R0, R_AUTO, R_ENG = 0.8, 1.2, 2.5

# Listening: daily probability = L0 + L_ENG * engagement; thinned before a lapse (set by hand).
L0, L_ENG = 0.02, 0.30
THIN_DAYS, THIN_FACTOR = 30, 0.35

IDS_PREFIX = "synthetic_"


def load_settings(path: Path = OPS_CONFIG) -> dict[str, Any]:
    """The registered seed and caps (configs/ops.yaml synthetic)."""
    return yaml.safe_load(path.read_text())["synthetic"]


def _ymd(d: date) -> int:
    return d.year * 10000 + d.month * 100 + d.day


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + np.exp(-x))


def _customer_ids(rng: np.random.Generator, n: int) -> list[str]:
    ids: set[str] = set()
    while len(ids) < n:
        ids.add(IDS_PREFIX + rng.bytes(8).hex())
    return sorted(ids)


def _simulate(
    rng: np.random.Generator, msno: str, kind: str
) -> tuple[list[dict], list[date], bool]:
    """Transaction rows, the days the customer is subscribed, and whether the last spell lapsed."""
    plan = int(rng.choice(list(PLANS), p=[v[1] for v in PLANS.values()]))
    price = PLANS[plan][0]
    method = int(rng.choice(PAYMENT_METHODS))
    auto = int(rng.random() < 0.65)
    start = DATA_START + timedelta(days=int(rng.integers(0, (LAST_JOIN - DATA_START).days + 1)))
    rows: list[dict] = []

    def row(day: date, expire: date, paid: int, listed: int, cancel: int = 0) -> None:
        rows.append(
            {
                "msno": msno,
                "payment_method_id": method,
                "payment_plan_days": plan,
                "plan_list_price": listed,
                "actual_amount_paid": paid,
                "is_auto_renew": auto,
                "transaction_date": _ymd(day),
                "membership_expire_date": _ymd(expire),
                "is_cancel": cancel,
            }
        )

    if kind == "trial_only":
        row(start, start + timedelta(days=7), 0, 0)
        return rows, [], False
    engagement = float(rng.beta(2, 3))
    day, lapsed, subscribed = start, False, []
    while day <= SIMULATION_END:
        expire = day + timedelta(days=plan)
        if kind == "discount100":
            row(day, expire, 0, price)
        else:
            paid = price // 2 if rng.random() < DISCOUNTED_ROW_SHARE else price
            row(day, expire, paid, price)
        subscribed.extend(day + timedelta(days=k) for k in range(plan))
        p_renew = _sigmoid(R0 + R_AUTO * auto + R_ENG * (engagement - 0.4))
        if rng.random() < p_renew:
            late = 0 if auto else int(rng.integers(0, LATE_RENEW_DAYS + 1))
            day = expire + timedelta(days=late)
            continue
        if rng.random() < CANCEL_BEFORE_LAPSE:
            lead = int(rng.integers(CANCEL_LEAD_DAYS[0], CANCEL_LEAD_DAYS[1] + 1))
            row(expire - timedelta(days=lead), expire, 0, price, cancel=1)
        if rng.random() < RETURN_AFTER_LAPSE:
            gap = int(rng.integers(RETURN_GAP_DAYS[0], RETURN_GAP_DAYS[1] + 1))
            day = expire + timedelta(days=gap)
            continue
        lapsed = True
        break
    # Listening depends on the engagement level, thinned shortly before a lapse.
    last_expire = max(d for d in subscribed) if subscribed else start
    days = []
    for d in subscribed:
        q = L0 + L_ENG * engagement
        if lapsed and (last_expire - d).days < THIN_DAYS:
            q *= THIN_FACTOR
        if d <= DATA_END and rng.random() < q:
            days.append(d)
    return rows, days, lapsed


def _log_rows(rng: np.random.Generator, msno: str, days: list[date]) -> list[dict]:
    out = []
    for d in days:
        n = rng.poisson(3, size=5)  # plays at 25%, 50%, 75%, 98.5% and 100% of a track
        unq = int(max(1, n.sum() - rng.integers(0, 2)))
        secs = float(max(30.0, rng.normal(180.0 * n.sum(), 60.0)))
        out.append(
            {
                "msno": msno,
                "date": _ymd(d),
                "num_25": int(n[0]),
                "num_50": int(n[1]),
                "num_75": int(n[2]),
                "num_985": int(n[3]),
                "num_100": int(n[4]),
                "num_unq": unq,
                "total_secs": round(secs, 3),
            }
        )
    return out


def _members(rng: np.random.Generator, ids: list[str]) -> pd.DataFrame:
    n = len(ids)
    registered = [_ymd(DATA_START - timedelta(days=int(k))) for k in rng.integers(0, 1500, size=n)]
    return pd.DataFrame(
        {
            "msno": ids,
            "city": rng.choice(CITIES, size=n),
            "bd": np.where(rng.random(n) < 0.6, 0, rng.integers(18, 61, size=n)),
            "gender": rng.choice(["male", "female", None], size=n, p=[0.35, 0.35, 0.30]),
            "registered_via": rng.choice(REGISTERED_VIA, size=n),
            "registration_init_time": registered,
        }
    )


def generate(out_dir: Path, settings: dict[str, Any] | None = None) -> dict[str, Any]:
    """Write the synthetic tables to `out_dir`; return a report that says it is synthetic.

    Raises ValueError when a registered size cap would be exceeded.
    """
    settings = settings or load_settings()
    cap = settings["size_cap"]
    rng = np.random.default_rng(int(settings["seed"]))
    ids = _customer_ids(rng, int(cap["customers"]))
    kinds = rng.choice(
        ["paid", "trial_only", "discount100"],
        size=len(ids),
        p=[1 - TRIAL_ONLY_SHARE - DISCOUNT100_SHARE, TRIAL_ONLY_SHARE, DISCOUNT100_SHARE],
    )
    tx_rows: list[dict] = []
    log_rows: list[dict] = []
    lapsed_ids: set[str] = set()
    for msno, kind in zip(ids, kinds, strict=True):
        rows, days, lapsed = _simulate(rng, msno, str(kind))
        tx_rows.extend(rows)
        log_rows.extend(_log_rows(rng, msno, days))
        if lapsed:
            lapsed_ids.add(msno)
    if len(log_rows) > int(cap["log_rows"]):
        raise ValueError(f"{len(log_rows)} log rows exceed the registered cap {cap['log_rows']}")

    tx = pd.DataFrame(tx_rows)
    tx = tx[tx.transaction_date <= _ymd(DATA_END)].reset_index(drop=True)
    logs = pd.DataFrame(log_rows)
    members = _members(rng, ids)
    # Stand-ins for the competition label tables: the customers whose last row is a lapse.
    last = tx[tx.is_cancel == 0].groupby("msno").membership_expire_date.max()
    train = pd.DataFrame({"msno": last.index, "is_churn": last.index.isin(lapsed_ids).astype(int)})
    split = train.msno.map(lambda m: int(m[-1], 16) % 2 == 0)
    out_dir.mkdir(parents=True, exist_ok=True)
    tables = {
        "synthetic_transactions": tx,
        "synthetic_transactions_v2": tx.iloc[0:0],
        "synthetic_user_logs": logs,
        "synthetic_user_logs_v2": logs.iloc[0:0],
        "synthetic_members": members,
        "synthetic_train": train[split],
        "synthetic_train_v2": train[~split],
    }
    sizes = {}
    for name, df in tables.items():
        path = out_dir / f"{name}.parquet"
        df.to_parquet(path, index=False, compression="zstd")
        sizes[path.name] = path.stat().st_size
    total = sum(sizes.values())
    if total > int(cap["total_files_bytes"]):
        raise ValueError(f"{total} bytes exceed the registered cap {cap['total_files_bytes']}")
    (out_dir / MARKER).write_text(SYNTHETIC_SENTENCE + "\n")
    report = {
        "synthetic": True,
        "label": SYNTHETIC_SENTENCE,
        "seed": int(settings["seed"]),
        "customers": len(ids),
        "rows": {n: len(d) for n, d in tables.items()},
        "file_bytes": sizes,
        "total_bytes": total,
        "caps": {
            "customers": int(cap["customers"]),
            "log_rows": int(cap["log_rows"]),
            "total_files_bytes": int(cap["total_files_bytes"]),
        },
        "data_end": str(DATA_END),
    }
    (out_dir / "synthetic_generate_report.json").write_text(json.dumps(report, indent=1) + "\n")
    return report
