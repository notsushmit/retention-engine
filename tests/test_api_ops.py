def write(directory: Path, name: str, content) -> Path:
    path = directory / name
    path.write_text(content if isinstance(content, str) else json.dumps(content))
    return path


def valid_retrain() -> dict:
    return {
        "run_date": "2026-11-01",
        "decision": OPS.decisions[1],
        "candidate_auc_30": 0.81,
        "current_auc_30": 0.8,
        "difference": 0.01,
        "interval_low": -0.002,
        "interval_high": 0.02,
        "rows": 100,
        "month": "2016-11-01",
        "synthetic": True,
        "serving_alias_unchanged": True,
        "label": OPS.retrain_label,
    }


# --- the registered strings ---
def test_the_registered_strings_are_read_from_the_config():
    assert OPS.synthetic_sentence == SYNTH
    assert OPS.drift_label.endswith("not that monitoring is effective in operation.")
    assert OPS.drift_see == "drift: see GET /drift (replayed 2016 data; mechanism demonstration)"
    assert DASH.drift == "drift: not monitored (Phase 10)"
    assert OPS.decisions == ("registered as candidate", "current model left in place")
    assert CFG["parameters"] == "none"


# --- the reader ---
def test_an_absent_file_answers_not_monitored_with_the_sentence_and_no_number(tmp_path):
    body = ops.drift_body(tmp_path)
    assert body == {"status": "not monitored", "label": DASH.drift}
    sch.DriftAbsent(**body)
    assert ops.drift_line(tmp_path) == DASH.drift and ops.last_retrain(tmp_path) is None


def test_a_valid_file_is_served_with_its_own_hash(tmp_path):
    path = write(tmp_path, ops.DRIFT_FILE, valid_drift())
    body = ops.drift_body(tmp_path)
    assert body["status"] == "monitored"
    assert body["report_sha256"] == hashlib.sha256(path.read_bytes()).hexdigest()
    assert body["label"] == OPS.drift_label + " " + SYNTH
    assert body["drift_share"] == 14 / 47 and body["dataset_alert"] is False
    assert list(body) == [
        "status",
        "report_sha256",
        "reference",
        "current",
        "columns_compared",
        "columns_drifted",
        "drift_share",
        "dataset_alert",
        "margin",
        "margin_met",
        "shifted",
        "batch_size",
        "library_defaults",
        "synthetic",
        "label",
    ]
    assert ops.drift_line(tmp_path) == OPS.drift_see


def test_a_file_that_is_not_synthetic_carries_only_the_registered_label(tmp_path):
    write(tmp_path, ops.DRIFT_FILE, valid_drift(synthetic=False))
    assert ops.drift_body(tmp_path)["label"] == OPS.drift_label


@pytest.mark.parametrize("bad", ["not json", "[]", "{}", json.dumps({"status": "monitored"})])
def test_an_unreadable_file_answers_unreadable_and_no_number(tmp_path, bad):
    write(tmp_path, ops.DRIFT_FILE, bad)
    assert ops.drift_body(tmp_path) == {"status": "unreadable", "label": DASH.drift}
    assert ops.drift_line(tmp_path) == DASH.drift


def test_a_file_over_one_megabyte_is_unreadable(tmp_path):
    big = valid_drift()
    big["reference"]["pad"] = "x" * (ops.MAX_BYTES + 1)
    write(tmp_path, ops.DRIFT_FILE, big)
    assert ops.drift_body(tmp_path)["status"] == "unreadable"


def test_a_wrong_label_is_unreadable(tmp_path):
    d = valid_drift()
    d["label"] = "Drift is monitored."
    write(tmp_path, ops.DRIFT_FILE, d)
    assert ops.drift_body(tmp_path)["status"] == "unreadable"


def test_a_column_named_after_a_never_used_attribute_is_removed_and_counted(tmp_path):
    d = valid_drift()
    d["columns_drifted"].append(
        {"column": "city", "method": "Jensen-Shannon distance", "threshold": 0.1, "statistic": 0.9}
    )
    write(tmp_path, ops.DRIFT_FILE, d)
    body = ops.drift_body(tmp_path)
    assert body["status"] == "monitored"
    assert [c["column"] for c in body["columns_drifted"]] == ["plays_28"]
    assert body["columns_compared"]["hidden_by_rule"] == 1
    assert sch.never_used_hits(json.dumps(body)) == []


@pytest.mark.parametrize("field", ["reference", "current", "library_defaults"])
@pytest.mark.parametrize("planted", ["A" * 43 + "=", "synthetic_0123456789abcdef", "tenure"])
def test_a_planted_id_or_never_used_word_in_a_field_makes_the_file_unreadable(
    tmp_path, field, planted
):
    d = valid_drift()
    d[field] = {"note": f"see {planted}"}
    write(tmp_path, ops.DRIFT_FILE, d)
    assert ops.drift_body(tmp_path)["status"] == "unreadable"


def test_the_body_holds_no_id_and_no_never_used_word(tmp_path):
    write(tmp_path, ops.DRIFT_FILE, valid_drift())
    text = json.dumps(ops.drift_body(tmp_path))
    assert sch.never_used_hits(text) == []
    assert_no_ids(text, ["synthetic_0123456789abcdef"], "the drift body")


def test_last_retrain_is_null_until_a_valid_file_exists(tmp_path):
    assert ops.last_retrain(tmp_path) is None
    write(tmp_path, ops.RETRAIN_FILE, valid_retrain())
    got = ops.last_retrain(tmp_path)
    assert got["decision"] == OPS.decisions[1] and got["serving_alias_unchanged"] is True
    assert got["label"] == OPS.retrain_label
    bad = valid_retrain() | {"decision": "promoted"}
    write(tmp_path, ops.RETRAIN_FILE, bad)
    assert ops.last_retrain(tmp_path) is None
    write(tmp_path, ops.RETRAIN_FILE, valid_retrain() | {"serving_alias_unchanged": False})
    assert ops.last_retrain(tmp_path) is None


def test_the_ops_folder_comes_from_the_environment(monkeypatch, tmp_path):
    monkeypatch.delenv(ops.OPS_DIR_ENV, raising=False)
    assert ops.ops_dir() == ops.DEFAULT_OPS_DIR
    monkeypatch.setenv(ops.OPS_DIR_ENV, str(tmp_path))
    assert ops.ops_dir() == tmp_path


# --- the endpoints ---
@pytest.mark.valkey
def test_get_drift_and_model_without_files(make_client, monkeypatch, tmp_path):  # noqa: F811
    monkeypatch.setenv(ops.OPS_DIR_ENV, str(tmp_path))
    c = make_client()
    r = c.get("/drift")
    assert r.status_code == 200 and r.json() == {"status": "not monitored", "label": DASH.drift}
    m = c.get("/model").json()
    assert m["drift"] == DASH.drift and m["last_retrain"] is None


@pytest.mark.valkey
def test_get_drift_and_model_with_files(make_client, monkeypatch, tmp_path):  # noqa: F811
    write(tmp_path, ops.DRIFT_FILE, valid_drift())
    write(tmp_path, ops.RETRAIN_FILE, valid_retrain())
    monkeypatch.setenv(ops.OPS_DIR_ENV, str(tmp_path))
    c = make_client()
    r = c.get("/drift")
    assert r.status_code == 200 and r.json()["status"] == "monitored"
    sch.DriftBody(**r.json())
    m = c.get("/model").json()
    assert m["drift"] == OPS.drift_see and m["last_retrain"]["rows"] == 100
    assert sch.never_used_hits(r.text) == [] and sch.never_used_hits(json.dumps(m)) == []


